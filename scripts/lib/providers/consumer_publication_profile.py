"""Explicit legacy GitHub formatting and caller environment bindings."""

class LegacyConsumerPublicationProfile:
    description = 'Publish allowlisted operational changes as a reviewed PR, never to main.'
    output_key = 'GITHUB_OUTPUT'
    summary_key = 'GITHUB_STEP_SUMMARY'
    ref_key = 'GITHUB_REF'
    repository_key = 'GITHUB_REPOSITORY'
    run_id_key = 'GITHUB_RUN_ID'
    attempt_key = 'GITHUB_RUN_ATTEMPT'
    author_name = 'github-actions[bot]'
    author_email = '41898282+github-actions[bot]@users.noreply.github.com'
    check_workflows = ('governance-ci.yml', 'codeql.yml', 'governance-repository-security.yml', 'consumer-lifecycle-guard.yml')

    @staticmethod
    def run_url(repository, run_id, attempt):
        return f'https://github.com/{repository}/actions/runs/{run_id}/attempts/{attempt}'

    @staticmethod
    def pulls_endpoint(repository):
        return f'repos/{repository}/pulls'

    @staticmethod
    def workflow_endpoint(repository, workflow):
        return f'repos/{repository}/actions/workflows/{workflow}/dispatches'

    @staticmethod
    def review_body(scope, run_id, attempt, head, run_url):
        return f'Generated by [workflow run {run_id}, attempt {attempt}]({run_url}).\n\nScope: `{scope}`. Proposed commit: `{head}`.\n\n' + ('Synthetic lifecycle proposal only; fixture consent is not human authentication and live activation remains disabled. ' if scope == 'lifecycle-synthetic' else '') + ('Scoped report-only operation-readiness consumer pilot; operating acceptance and personal action consent are independently verified. ' if scope == 'consumer-lifecycle' else '') + 'Only allowlisted operational evidence and projections are included. The official indexes and viewer change only after review and merge. No automatic approval or merge is performed.\n\nReview new snapshots, failures, conflicts, and provenance before merging. If main advances, reconcile and regenerate the projections on the updated branch and rerun checks; do not overwrite append-only evidence.\n\nGovernance CI, CodeQL, self-security and Consumer Lifecycle Guard are explicitly dispatched for this branch. If GitHub also queues PR workflows for approval, a maintainer must approve those runs.'

    @staticmethod
    def api_command(endpoint):
        return ['gh', 'api', '--method', 'POST', endpoint, '--input', '-']
